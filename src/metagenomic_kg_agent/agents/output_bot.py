"""
Output Bot for the multi-agent computational biology framework.

Responsibilities:
1. Receive aggregated execution results from Orchestrator.
2. Parse and consolidate results from multiple KG queries.
3. Interpret biological relationships.
4. Report successful, failed and skipped tasks.
5. Generate the final scientific response.

The Output Bot does not execute queries or analyses.
"""

import json

from langchain_core.messages import SystemMessage, HumanMessage


# ============================================================
# 1. OUTPUT BOT SYSTEM PROMPT
# ============================================================

OUTPUT_BOT_PROMPT = """
You are the Output Bot of a multi-agent computational biology
and metagenomic knowledge graph framework.

Your responsibility is to generate the final response to the
user using the execution results supplied by the Orchestrator.

You will receive:

1. Original user question.
2. Execution plan generated by the Validator.
3. Results from individual knowledge graph queries.
4. Knowledge graph names and operations.
5. Completed tasks.
6. Failed tasks.
7. Skipped tasks.
8. Overall execution status.

============================================================
YOUR RESPONSIBILITIES
============================================================

1. Understand the original user question.

2. Consolidate results from all successfully executed tasks.

3. Identify relationships between results obtained from
   different tasks.

4. Present biological entities and relationships clearly.

5. Explain the results in the context of the original question.

6. Report incomplete tasks and execution failures.

7. Identify limitations in the retrieved evidence.

============================================================
SCIENTIFIC ACCURACY RULES
============================================================

1. Use only the information supplied by the Orchestrator.

2. Never invent biological entities, relationships,
   experimental results, statistics or scientific conclusions.

3. Clearly distinguish retrieved evidence from interpretation.

4. Do not infer causation from biological associations.

5. Distinguish between:
   - produces
   - metabolizes
   - associated_with
   - interacts_with
   - correlated_with

6. Do not assume that two different knowledge graph IRIs
   represent the same biological entity unless this is
   explicitly established in the supplied results.

7. Do not interpret missing KG results as proof that
   a biological relationship does not exist.

8. If a task returns no results, explicitly state that
   no matching records were retrieved.

9. If a task fails, communicate the failure.

10. If a dependent task was skipped, explain that its
    prerequisite task did not complete successfully.

11. Never claim that an analysis was performed if it
    was not executed.

============================================================
RESULT AGGREGATION
============================================================

When multiple tasks are executed:

- Combine related results.
- Avoid unnecessarily repeating identical records.
- Preserve the knowledge graph source of each result.
- Connect dependent task results where appropriate.
- Do not combine unrelated biological relationships.

When multiple knowledge graphs are involved:

- Identify which graph supplied each result.
- Preserve differences in entity identifiers.
- Do not claim entity equivalence without evidence.

============================================================
EXECUTION STATUS
============================================================

completed:
All tasks were successfully executed.

partially_completed:
Some tasks succeeded, but others failed or were skipped.

failed:
No tasks completed successfully.

============================================================
RESPONSE FORMAT
============================================================

Generate a clear scientific response.

Use the following structure where appropriate:

1. Answer
   Directly address the user's question.

2. Retrieved Results
   Present the biological entities and relationships.

3. Interpretation
   Explain what the retrieved information indicates.
   Do not make unsupported scientific claims.

4. Execution Summary
   Report completed, failed and skipped tasks.

5. Limitations
   Mention missing results, unavailable capabilities
   and other relevant limitations.

6. Knowledge Graph Sources
   Identify the knowledge graphs used.

Do not include empty sections unnecessarily.

If no results were retrieved, clearly explain this.

Your final response must be understandable to a
computational biology researcher as well as a
wet-lab biologist.

Return the final scientific response only.
"""


# ============================================================
# 2. HELPER: EXTRACT MESSAGE CONTENT
# ============================================================

def _extract_message_content(messages):

    if not messages:
        return ""

    content = messages[-1].content

    if isinstance(content, list):

        content = " ".join(
            item.get("text", "")
            for item in content
            if isinstance(item, dict)
        )

    return str(content)


# ============================================================
# 3. HELPER: PREPARE EXECUTION CONTEXT
# ============================================================

def _prepare_execution_context(state):

    # The new Orchestrator passes aggregated_results
    # directly through execution_data.

    execution_data = state.get(
        "execution_data",
        {}
    )

    if not execution_data:

        # Also support direct invocation with
        # aggregated_results in the state.

        execution_data = state.get(
            "aggregated_results",
            {}
        )

    if not execution_data:

        execution_data = {}

    original_request = execution_data.get(
        "original_question",
        state.get("original_question", "")
    )

    if not original_request:

        original_request = _extract_message_content(
            state.get("messages", [])
        )

    context = {

        "original_request": original_request,

        "execution_plan": execution_data.get(
            "execution_plan",
            state.get("execution_plan", [])
        ),

        "execution_results": execution_data.get(
            "execution_results",
            {}
        ),

        "completed_tasks": execution_data.get(
            "completed_tasks",
            []
        ),

        "failed_tasks": execution_data.get(
            "failed_tasks",
            []
        ),

        "skipped_tasks": execution_data.get(
            "skipped_tasks",
            []
        ),

        "execution_status": execution_data.get(
            "execution_status",
            state.get("execution_status", "unknown")
        ),

        "validation_status": state.get(
            "validation_status"
        ),

        "missing_information": state.get(
            "missing_information",
            []
        ),

        "unsupported_tasks": state.get(
            "unsupported_tasks",
            []
        ),

        "unavailable_capabilities": state.get(
            "unavailable_capabilities",
            []
        ),

        "errors": state.get(
            "errors",
            []
        )
    }

    return context


# ============================================================
# 4. BUILD OUTPUT BOT
# ============================================================

def build_output_bot(model_registry):

    llm = model_registry.get_model("output_bot")

    def output_bot(state):

        # ----------------------------------------------------
        # Step 1: Retrieve Orchestrator execution data
        # ----------------------------------------------------

        context = _prepare_execution_context(state)

        if not context["original_request"]:

            return {
                "final_response": (
                    "The original user request could not be "
                    "identified."
                ),
                "output_status": "output_failed",
                "errors": [
                    "Missing original user request."
                ]
            }

        if not context["execution_results"]:

            if context["execution_status"] in {
                "needs_input",
                "unsupported"
            }:

                return {
                    "final_response": (
                        "The request could not be executed. "
                        + str(
                            context["missing_information"]
                        )
                    ),
                    "output_status": "completed",
                    "execution_status": context[
                        "execution_status"
                    ]
                }

            return {
                "final_response": (
                    "The Orchestrator did not provide any "
                    "knowledge graph execution results."
                ),
                "output_status": "completed",
                "execution_status": context[
                    "execution_status"
                ]
            }

        # ----------------------------------------------------
        # Step 2: Prepare LLM input
        # ----------------------------------------------------

        user_prompt = f"""
ORIGINAL USER REQUEST:

{context["original_request"]}


EXECUTION PLAN:

{json.dumps(
    context["execution_plan"],
    indent=2,
    default=str
)}


EXECUTION RESULTS:

{json.dumps(
    context["execution_results"],
    indent=2,
    default=str
)}


COMPLETED TASKS:

{json.dumps(context["completed_tasks"])}


FAILED TASKS:

{json.dumps(context["failed_tasks"])}


SKIPPED TASKS:

{json.dumps(context["skipped_tasks"])}


OVERALL EXECUTION STATUS:

{context["execution_status"]}


MISSING INFORMATION:

{json.dumps(context["missing_information"])}


UNSUPPORTED TASKS:

{json.dumps(context["unsupported_tasks"])}


UNAVAILABLE CAPABILITIES:

{json.dumps(context["unavailable_capabilities"])}


EXECUTION ERRORS:

{json.dumps(context["errors"], default=str)}


Generate the final scientific response.

Use only the supplied execution evidence.
"""

        # ----------------------------------------------------
        # Step 3: Invoke Output LLM
        # ----------------------------------------------------

        try:

            response = llm.invoke([

                SystemMessage(
                    content=OUTPUT_BOT_PROMPT
                ),

                HumanMessage(
                    content=user_prompt
                )

            ])

            final_response = getattr(
                response,
                "content",
                response
            )

            if isinstance(final_response, list):

                final_response = " ".join(
                    item.get("text", "")
                    for item in final_response
                    if isinstance(item, dict)
                )

            final_response = str(
                final_response
            ).strip()

            # ------------------------------------------------
            # Step 4: Return final response
            # ------------------------------------------------

            return {

                "final_response": final_response,

                "output_status": "completed",

                # Preserve the actual Orchestrator status.
                "execution_status": context[
                    "execution_status"
                ],

                "execution_summary": {

                    "completed": len(
                        context["completed_tasks"]
                    ),

                    "failed": len(
                        context["failed_tasks"]
                    ),

                    "skipped": len(
                        context["skipped_tasks"]
                    )
                },

                "knowledge_graph_sources": list(
                    dict.fromkeys(
                        result.get("knowledge_graph")
                        for result in context[
                            "execution_results"
                        ].values()
                        if isinstance(result, dict)
                        and result.get("knowledge_graph")
                    )
                )

            }

        except Exception as error:

            return {

                "final_response": (
                    "An error occurred while generating "
                    "the final scientific response. "
                    "The underlying Orchestrator results "
                    "have been preserved."
                ),

                "output_status": "output_failed",

                "execution_status": context[
                    "execution_status"
                ],

                "errors": [str(error)]

            }

    return output_bot